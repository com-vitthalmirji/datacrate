//! Renders a standalone `main()` that wires `ContractPipeline` end-to-end:
//! register a source, run an optional SQL transform stage, and write the
//! result via `pipeline::write_parquet` — never touching a row-major
//! buffer, so "no transpose" holds by construction (the same property
//! `crates/pipeline/src/bin/zero-transpose-end-to-end.rs` already proves by
//! hand).
//!
//! The emitted file depends on `typestate`, `pipeline`, `contracts`,
//! `connectors-derive`, and `datafusion` (and `deltalake` when the source
//! format is Delta). `crates/typestate/examples/` is this repo's proven
//! home for it: `typestate` depends on `pipeline`, so a
//! `ContractPipeline`-using binary placed in `crates/pipeline/src/bin/`
//! instead would create a dependency cycle.

use crate::dataframe_ops::{self, DfOp};
use crate::{SchemaCodegenError, struct_source};
use arrow_schema::Schema;
use proc_macro2::TokenStream;
use quote::{format_ident, quote};

/// Where a generated pipeline's source data physically lives at run time.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum SourceFormat {
    /// A Parquet file, read via `register_parquet`.
    Parquet,
    /// A CSV file, read via `register_csv`.
    Csv,
    /// A Delta table, read via `deltalake::open_table` + DataFusion.
    Delta,
}

/// The physical source a generated pipeline reads from at run time.
#[derive(Debug, Clone)]
pub struct SourceData<'a> {
    /// A file path (Parquet/Csv) or table URI (Delta).
    pub location: &'a str,
    /// Which [`SourceFormat`] `location` is read as.
    pub format: SourceFormat,
}

/// The transform stage of a generated pipeline: either a SQL string
/// (`ContractPipeline::sql_transform`) or a DataFusion `DataFrame`-API op
/// chain (`ContractPipeline::dataframe_transform`). Both query/operate on the
/// literal table name `batch`.
#[derive(Debug, Clone)]
pub enum TransformSpec<'a> {
    /// SQL text, passed verbatim to `sql_transform`.
    Sql(&'a str),
    /// A closed chain of `DfOp`s, rendered into real `.select()/.filter()/...`
    /// calls and passed to `dataframe_transform`.
    DataFrame(Vec<DfOp>),
}

/// Everything needed to render one generated pipeline binary.
pub struct PipelineSpec<'a> {
    /// Base name for the generated struct(s): `<name>Source`, and
    /// `<name>Target` only when `target_schema` is set.
    pub name: &'a str,
    /// The source's declared shape.
    pub source_schema: &'a Schema,
    /// The target's declared shape. `None` means passthrough: the source
    /// struct is reused as the sink's contract and no transform stage is
    /// emitted.
    pub target_schema: Option<&'a Schema>,
    /// Where the source data physically lives at run time.
    pub source_data: SourceData<'a>,
    /// The transform stage. `None` skips it entirely.
    pub transform: Option<TransformSpec<'a>>,
    /// The one sink: a Parquet file path, written via `pipeline::write_parquet`.
    pub sink_parquet: &'a str,
}

const HEADER: &str = "//! Generated by `scaffold-cli pipeline`. Depends on `typestate`, `pipeline`,\n\
//! `contracts`, `connectors-derive`, and `datafusion` (and `deltalake` for a\n\
//! Delta source) — place this file in `crates/typestate/examples/`, which\n\
//! already has every one of them. Do not place it in\n\
//! `crates/pipeline/src/bin/`: `typestate` depends on `pipeline`, so a\n\
//! `ContractPipeline`-using binary there would create a dependency cycle.\n\
//!\n\
//! The source is registered schema-on-write (the declared schema is set\n\
//! explicitly on the table, not inferred from the file/table itself), so a\n\
//! source whose physical shape drifts from the declared one fails at scan\n\
//! time instead of silently being read under the wrong schema.\n\
#![allow(dead_code, unused_imports)]\n\n\
use connectors_derive::Connector;\n\
use contracts::Contract;\n\
use datafusion::prelude::SessionContext;\n\
use object_store::ObjectStoreExt;\n\
use parquet::basic::Compression;\n\
use pipeline::write_parquet;\n\
use std::path::Path;\n\
use typestate::contract_pipeline::{CallbackError, ContractPipeline};\n\n";

/// Splits an `s3://bucket/key` location into `(bucket, key)`. Returns `None`
/// for any other scheme (local paths, `file://`, Delta table URIs) — those
/// need no object-store registration.
fn parse_s3_location(location: &str) -> Option<(&str, &str)> {
    location.strip_prefix("s3://")?.split_once('/')
}

/// Registers an S3-compatible object store for `location`'s bucket on the
/// `SessionContext`'s `RuntimeEnv`, if `location` is an `s3://` URL.
///
/// Credentials and endpoint come from the standard AWS environment
/// variables (`AWS_ACCESS_KEY_ID`, `AWS_SECRET_ACCESS_KEY`,
/// `AWS_ENDPOINT_URL`, `AWS_REGION`, `AWS_ALLOW_HTTP`), picked up by
/// `AmazonS3Builder::from_env()` — the same pattern
/// `crates/pipeline/src/bin/run-s3-pipeline.rs` already uses. A real AWS S3
/// bucket and a local MinIO container are both just "S3" to this code; only
/// which environment variables are set at run time differs, not the
/// generated code path.
fn s3_registration_tokens(location: &str) -> Option<TokenStream> {
    let (bucket, _key) = parse_s3_location(location)?;
    let store_url = format!("s3://{bucket}");
    Some(quote! {
        {
            let store = object_store::aws::AmazonS3Builder::from_env()
                .with_bucket_name(#bucket)
                .build()?;
            ctx.runtime_env()
                .register_object_store(&url::Url::parse(#store_url)?, std::sync::Arc::new(store));
        }
    })
}

/// Renders the registration statement(s) that bind the literal table name
/// `batch` to `data`'s physical source, dispatched per [`SourceFormat`].
fn registration_tokens(source_struct_name: &str, data: &SourceData<'_>) -> TokenStream {
    let source_struct_ident = format_ident!("{source_struct_name}");
    let location = data.location;
    match data.format {
        SourceFormat::Parquet => quote! {
            #source_struct_ident::register_parquet(&ctx, "batch", #location)?;
        },
        SourceFormat::Csv => quote! {
            #source_struct_ident::register_csv(&ctx, "batch", #location)?;
        },
        SourceFormat::Delta => quote! {
            runtime.block_on(async {
                let table = deltalake::open_table(#location).await?;
                table.update_datafusion_session(&ctx.state())?;
                let provider = table.table_provider().await?;
                ctx.register_table("batch", provider)?;
                Ok::<(), Box<dyn std::error::Error>>(())
            })?;
        },
    }
}

/// Renders the transform stage, dispatched per [`TransformSpec`]: a
/// `.sql_transform(...)` call, a `.dataframe_transform(...)` call built from
/// `dataframe_ops::chain_tokens`, or nothing when `transform` is `None`.
fn transform_tokens(
    transform: &Option<TransformSpec<'_>>,
    target_struct_name: &str,
) -> TokenStream {
    let target_ident = format_ident!("{target_struct_name}");
    match transform {
        Some(TransformSpec::Sql(sql)) => quote! {
            .sql_transform::<#target_ident>(&ctx, #sql)
        },
        Some(TransformSpec::DataFrame(ops)) => {
            let chain = dataframe_ops::chain_tokens(ops);
            quote! {
                .dataframe_transform::<#target_ident>(&ctx, |df| Ok(#chain))
            }
        }
        None => TokenStream::new(),
    }
}

/// Renders the sink closure passed to `.sink::<Target>(...)`, plus an
/// optional helper function to emit alongside it when the sink is `s3://`.
/// A local-path sink keeps using `write_parquet` directly, unchanged; an
/// `s3://` sink writes to a local temp file first (reusing `write_parquet`
/// as-is) then uploads those bytes — the object store is just where the
/// already-written Parquet file ends up, not a different write path.
fn sink_tokens(sink_parquet: &str) -> (TokenStream, Option<TokenStream>) {
    match parse_s3_location(sink_parquet) {
        Some((bucket, key)) => {
            let helper = quote! {
                fn put_object_s3(bucket: &str, key: &str, bytes: Vec<u8>) -> Result<(), CallbackError> {
                    let rt = tokio::runtime::Builder::new_current_thread()
                        .enable_all()
                        .build()
                        .map_err(|e| Box::new(e) as CallbackError)?;
                    let store = object_store::aws::AmazonS3Builder::from_env()
                        .with_bucket_name(bucket)
                        .build()
                        .map_err(|e| Box::new(e) as CallbackError)?;
                    rt.block_on(store.put(&object_store::path::Path::from(key), bytes.into()))
                        .map_err(|e| Box::new(e) as CallbackError)?;
                    Ok(())
                }
            };
            let sink = quote! {
                move |batch| {
                    let tmp = tempfile::NamedTempFile::new().map_err(|e| Box::new(e) as CallbackError)?;
                    write_parquet(&batch, tmp.path(), Compression::SNAPPY)
                        .map_err(|e| Box::new(e) as CallbackError)?;
                    let bytes = std::fs::read(tmp.path()).map_err(|e| Box::new(e) as CallbackError)?;
                    put_object_s3(#bucket, #key, bytes)
                }
            };
            (sink, Some(helper))
        }
        None => {
            let sink = quote! {
                move |batch| {
                    write_parquet(&batch, Path::new(#sink_parquet), Compression::SNAPPY)
                        .map_err(|e| Box::new(e) as CallbackError)
                }
            };
            (sink, None)
        }
    }
}

/// Renders a standalone `main()` wiring `ContractPipeline` end-to-end, per
/// `spec`.
///
/// # Errors
/// Returns [`SchemaCodegenError::InvalidFieldName`] or
/// [`SchemaCodegenError::UnsupportedArrowType`] under the same conditions as
/// [`struct_source`], for either the source or target schema.
pub fn pipeline_source(spec: &PipelineSpec) -> Result<String, SchemaCodegenError> {
    let source_struct_name = format!("{}Source", spec.name);
    let source_struct_text = struct_source(&source_struct_name, spec.source_schema)?;

    let (target_struct_text, target_struct_name) = match spec.target_schema {
        Some(target_schema) => {
            let target_struct_name = format!("{}Target", spec.name);
            let text = struct_source(&target_struct_name, target_schema)?;
            (Some(text), target_struct_name)
        }
        None => (None, source_struct_name.clone()),
    };

    let source_store = s3_registration_tokens(spec.source_data.location);
    let sink_store = s3_registration_tokens(spec.sink_parquet);
    let registration = registration_tokens(&source_struct_name, &spec.source_data);
    let transform_stage = transform_tokens(&spec.transform, &target_struct_name);
    let (sink, sink_helper) = sink_tokens(spec.sink_parquet);

    let source_ident = format_ident!("{source_struct_name}");
    let target_ident = format_ident!("{target_struct_name}");

    let main_fn = quote! {
        #sink_helper

        fn main() -> Result<(), Box<dyn std::error::Error>> {
            let runtime = tokio::runtime::Builder::new_current_thread()
                .enable_all()
                .build()?;
            let ctx = SessionContext::new();

            #source_store
            #sink_store
            #registration

            let batches = runtime.block_on(async { ctx.table("batch").await?.collect().await })?;

            let report = ContractPipeline::source::<#source_ident, _>(move || {
                Ok(batches.into_iter().map(Ok))
            })
            #transform_stage
            .sink::<#target_ident>(#sink)
            .build()?
            .run()?;

            println!("batches_processed={}", report.batches_processed);
            println!("rows_processed={}", report.rows_processed);
            Ok(())
        }
    };

    let file: syn::File =
        syn::parse2(main_fn).map_err(|source| SchemaCodegenError::RenderMain { source })?;
    let main_text = prettyplease::unparse(&file);

    let mut out = String::from(HEADER);
    out.push_str(&source_struct_text);
    if let Some(target_struct_text) = target_struct_text {
        out.push_str(&target_struct_text);
    }
    out.push('\n');
    out.push_str(&main_text);
    Ok(out)
}
